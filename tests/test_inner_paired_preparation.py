def completed_one_axis(tmp_path):
    normal,contract=fixture();normal['provenance']={'source':'normal source'}
    cases=make_one_axis_cases(normal,screen(normal,contract),tmp_path/'normal')
    plan=dict(schema='aldp_inner_continuation_plan_v1',study_stage='one_axis',cases=cases,
        curve_contract=contract,frozen_inputs={},source_manifest_sha256='tested-continuation-source',
        cached_reference_paid_openmm=285376)
    one_axis=tmp_path/'one_axis';one_axis.mkdir()
    (one_axis/'plan.json').write_text(json.dumps(plan))
    policy=normal['diagnostics']['inner_boundaries'][-1]['policy']
    reports={}
    for name,cost in [('normal',260224),('u_short',38592),('h_short',260032)]:
        out=one_axis/'continuation'/name;out.mkdir(parents=True)
        report=dict(provenance={'source':'tested-continuation-source','case':name},
            diagnostics={'first_outer_complete':deepcopy(policy),'trained_policy':deepcopy(policy),
                'first_outer_validation':{'heldout_loss':1.},'next_outer_validation':{'heldout_loss':1.},
                'first_outer_own_h_validation':{'heldout_loss':1.},'inner_boundaries':[]},
            cost={'total_openmm_configurations':cost},new_optimizer_steps=1,cached_global_step=1,
            cached_reference_paid_openmm=285376)
        files={}
        if name=='u_short':
            snapshot=out/'inner_snapshots/outer001_h_0125.pt';snapshot.parent.mkdir()
            snapshot.write_bytes(b'fixture: coupled u250 h125 boundary, not a usable tensor checkpoint')
            batch=out/'heldout_h_outer001.pt'
            batch.write_bytes(b'fixture: endpoints generated by shortened u')
            report['diagnostics']['inner_boundaries'].append(dict(outer_loop=1,phase='h',phase_epoch=125,
                snapshot=str(snapshot.relative_to(out)),validation={'heldout_loss':1.}))
            files.update({str(snapshot.relative_to(out)):sha256(snapshot),batch.name:sha256(batch)})
        (out/'result.json').write_text(json.dumps(report))
        files['result.json']=sha256(out/'result.json')
        (out/'receipt.json').write_text(json.dumps({'files':files}))
        reports[name]=report
    audit=one_axis/'monitor_state.json'
    audit.write_text(json.dumps(dict(status='continuations_verified',source_sha256='tested-continuation-source',
        plan_sha256=sha256(one_axis/'plan.json'),results_sha256={name:sha256(one_axis/'continuation'/name/'result.json') for name in cases})))
    return one_axis,audit,reports


def test_paired_preparation_uses_coupled_h_prefix_and_frozen_audit(tmp_path):
    one_axis,audit,reports=completed_one_axis(tmp_path)
    paired=tmp_path/'paired'
    plan=prepare_paired(one_axis,audit,paired,'tested-continuation-source')
    case=plan['cases']['paired']
    assert (case['u_epochs'],case['h_epochs'],case['cached_global_step'])==(250,125,37500)
    assert case['checkpoint_path']==str(one_axis/'continuation/u_short/inner_snapshots/outer001_h_0125.pt')
    assert case['first_h_validation_path']==str(one_axis/'continuation/u_short/heldout_h_outer001.pt')
    assert case['expected_provenance']==reports['u_short']['provenance']
    assert not case['reuse_first_outer_policy']
    copied=paired/'one_axis_completion_audit.json'
    digest=plan['frozen_inputs'][str(copied)]
    audit.write_text('{"status":"later monitor revision"}')
    assert str(audit) not in plan['frozen_inputs'] and sha256(copied)==digest
    assert plan['cached_upstream_completed_openmm']==844224
    report=deepcopy(reports['u_short']);report['cost']['total_openmm_configurations']=37760
    decision=compare_paired(report,plan)
    assert decision['pair_status']=='paired_confirmation_passed'
    assert decision['paid_study_openmm_configurations']==881984
    assert decision['minimum_inner_duration']=='not_established'


def test_paired_preparation_rejects_changed_receipt_and_failed_accounting(tmp_path):
    one_axis,audit,reports=completed_one_axis(tmp_path)
    payload=json.loads(audit.read_text());payload['status']='active'
    audit.write_text(json.dumps(payload))
    with pytest.raises(ValueError,match='Verified one-axis'):
        prepare_paired(one_axis,audit,tmp_path/'paired','tested-continuation-source')
    payload['status']='continuations_verified';audit.write_text(json.dumps(payload))
    checkpoint=one_axis/'continuation/u_short/inner_snapshots/outer001_h_0125.pt'
    checkpoint.write_bytes(b'altered coupled boundary')
    with pytest.raises(ValueError,match='receipt path/SHA mismatch'):
        prepare_paired(one_axis,audit,tmp_path/'paired','tested-continuation-source')
    assert not (tmp_path/'paired').exists()
